const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const code=fs.readFileSync('app/src/main/assets/skin-paint-core.js','utf8');
const root={};vm.runInNewContext(code,{window:root});
const p=root.PortSkinPaintCore;
const rgba=(img,x,y)=>[...img.data.slice((y*img.width+x)*4,(y*img.width+x)*4+4)];
function image(w,h){return {width:w,height:h,data:new Uint8ClampedArray(w*h*4)};}
const test=image(8,8);
assert.equal(p.putPixel(test,2,2,[255,0,0,255],1),1);
assert.deepEqual(rgba(test,2,2),[255,0,0,255]);
assert.equal(p.drawLine(test,2,2,2,5,[0,255,0,255],1),4);
assert.deepEqual(rgba(test,2,5),[0,255,0,255]);
assert.deepEqual(rgba(test,2,4),[0,255,0,255]);
assert.equal(p.floodFill(test,0,0,[0,0,255,255]),60);
assert.deepEqual(rgba(test,0,0),[0,0,255,255]);
assert.deepEqual(rgba(test,2,2),[0,255,0,255]);
assert.deepEqual({...p.pixelFromUV(0,.999,64,64)},{x:0,y:0});
assert.deepEqual({...p.pixelFromUV(.5,.5,64,64)},{x:32,y:32});
assert.equal(p.pixelFromUV(-.1,.5,64,64),null);
const face=image(4,2);
for(let y=0;y<2;y++)for(let x=0;x<4;x++)p.putPixel(face,x,y,[x+y*4,0,0,255],1);
const initial=[...face.data];
p.flipFace(face,[0,0,4,2],'horizontal');
assert.deepEqual(rgba(face,0,0),[3,0,0,255]);
assert.deepEqual(rgba(face,3,1),[4,0,0,255]);
p.flipFace(face,[0,0,4,2],'horizontal');
assert.deepEqual([...face.data],initial,'Double horizontal flip restores pixels');
p.flipFace(face,[0,0,4,2],'vertical');
assert.deepEqual(rgba(face,0,0),[4,0,0,255]);
p.flipFace(face,[0,0,4,2],'vertical');
assert.deepEqual([...face.data],initial,'Double vertical flip restores pixels');
p.flipFace(face,[0,0,4,2],'rotate180');
assert.deepEqual(rgba(face,0,0),[7,0,0,255]);
p.flipFace(face,[0,0,4,2],'rotate180');
assert.deepEqual([...face.data],initial);
p.copyFace(face,[0,0,2,1],[2,0,4,1],true);
assert.deepEqual(rgba(face,2,0),[1,0,0,255]);
assert.deepEqual(rgba(face,3,0),[0,0,0,255]);
const clipped=image(8,8);
assert.equal(p.floodFill(clipped,1,1,[120,80,40,255],2000000,{x:0,y:0,w:4,h:4}),16);
assert.deepEqual(rgba(clipped,1,1),[120,80,40,255]);
assert.deepEqual(rgba(clipped,6,6),[0,0,0,0],'Fill must not spill outside selected UV face');
assert.equal(p.floodFill(clipped,7,7,[255,20,20,255],2000000,{x:0,y:0,w:4,h:4}),0);
console.log('PASS: pencil, line, bounded fill, UV coordinates, horizontal/vertical/180 flip, face copy');
